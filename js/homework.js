function rotateRow(row, index) {
  const options = [...row[1]];
  const shift = index % 3;
  for (let k = 0; k < shift; k++) options.unshift(options.pop());
  return {
    q: row[0],
    options,
    answer: (row[2] + shift) % 3,
  };
}

function buildChinese() {
  return CN_ROWS.map((row, i) => {
    const item = rotateRow(row, i);
    return { id: 'cn' + (i + 1), subject: '语文', q: item.q, options: item.options, answer: item.answer };
  });
}

function buildEnglish() {
  return EN_ROWS.map((row, i) => {
    const item = rotateRow(row, i);
    return { id: 'e' + (i + 1), subject: '英语', q: item.q, options: item.options, answer: item.answer };
  });
}

function buildMath() {
  return MATH_ROWS.map(([op, a, b], i) => {
    const answer = op === '+' ? a + b : op === '-' ? a - b : a * b;
    const candidates = [answer + 1, answer - 1, answer + 2, answer - 2, answer + 3, answer - 3]
      .filter(v => v >= 0 && v !== answer);
    const wrong = [...new Set(candidates)].slice(0, 2);
    const base = [String(answer), ...wrong.map(String)];
    const shift = i % 3;
    const options = [...base];
    for (let k = 0; k < shift; k++) options.unshift(options.pop());
    const word = op === '+' ? '加' : op === '-' ? '减' : '乘';
    return {
      id: 'm' + (i + 1),
      subject: '数学',
      q: `${a} ${word} ${b} 等于几？`,
      options,
      answer: shift,
    };
  });
}

